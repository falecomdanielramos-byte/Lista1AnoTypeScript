// 5- Faça um algoritmo que receba dois números e ao final mostre a soma, subtração,
// multiplicação e a divisão dos números lidos.


export function questao03():void{


    let nu1:number=Number(prompt("Informe um número: "))
    let nu2:number=Number(prompt("Informe outro número: "))


    window.alert(`A soma dos números é: ${nu1+nu2}`)
    window.alert(`A subtração dos números é: ${nu1-nu2}`)
    window.alert(`A multiplicação dos números é: ${nu1*nu2}`)
    window.alert(`A divisão dos números é: ${nu1/nu2}`)







}